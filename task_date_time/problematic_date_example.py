"""
Проблемный пример работы с датой и временем
Демонстрирует недостатки наивного подхода к парсингу дат.

Этот код аналогичен проблемному Java коду с SimpleDateFormat и имеет те же недостатки.
"""

from datetime import datetime
from typing import Optional


def parse_date_naive(date_string: str) -> datetime:
    """
    ПРОБЛЕМНАЯ функция парсинга даты.
    Аналогична Java коду с SimpleDateFormat.
    
    Args:
        date_string: Строка с датой в формате "YYYY-MM-DD HH:MM:SS"
    
    Returns:
        Объект datetime (без информации о часовом поясе)
    
    Проблемы:
    1. Нет информации о часовом поясе (naive datetime)
    2. Нет валидации входных данных
    3. Нет обработки ошибок парсинга
    4. Зависит от системного часового пояса при выводе
    5. Не учитывает переходы на летнее/зимнее время
    """
    format_str = "%Y-%m-%d %H:%M:%S"
    date = datetime.strptime(date_string, format_str)
    return date


def demonstrate_problems():
    """
    Демонстрация проблем с наивным подходом к работе с датами.
    """
    print("=" * 70)
    print("ДЕМОНСТРАЦИЯ ПРОБЛЕМ: Наивный парсинг дат")
    print("=" * 70)
    
    # Пример 1: Успешный парсинг, но без timezone
    print("\n1. Парсинг даты без указания часового пояса:")
    date_string = "2024-05-13 14:30:00"
    date = parse_date_naive(date_string)
    print(f"   Входная строка: {date_string}")
    print(f"   Результат: {date}")
    print(f"   Часовой пояс: {date.tzinfo} (None = нет информации!)")
    print("   ПРОБЛЕМА: Непонятно, в каком часовом поясе эта дата!")
    
    # Пример 2: Что происходит при сравнении с UTC?
    print("\n2. Проблема сравнения с UTC:")
    from datetime import timezone
    utc_now = datetime.now(timezone.utc)
    naive_date = parse_date_naive(date_string)
    print(f"   UTC время: {utc_now}")
    print(f"   Наивная дата: {naive_date}")
    print("   ПРОБЛЕМА: Сравнение naive datetime с aware datetime вызывает ошибку!")
    try:
        # Это вызовет TypeError
        diff = utc_now - naive_date
    except TypeError as e:
        print(f"   ОШИБКА: {e}")
    
    # Пример 3: Нет валидации - некорректный формат
    print("\n3. Отсутствие валидации входных данных:")
    invalid_strings = [
        "",  # Пустая строка
        "2024-13-45 25:70:99",  # Некорректные значения
        "13.05.2024 14:30",  # Другой формат
        "not a date",  # Вообще не дата
    ]
    
    for invalid_str in invalid_strings:
        try:
            result = parse_date_naive(invalid_str)
            print(f"   '{invalid_str}' -> {result} (неожиданно успешно!)")
        except ValueError as e:
            print(f"   '{invalid_str}' -> ValueError: {e}")
            print("   ПРОБЛЕМА: Ошибка не обрабатывается, программа падает!")
    
    # Пример 4: Зависимость от системного часового пояса
    print("\n4. Зависимость от системного часового пояса:")
    naive_date = parse_date_naive("2024-05-13 14:30:00")
    print(f"   Наивная дата: {naive_date}")
    print(f"   Системный часовой пояс: {datetime.now().astimezone().tzinfo}")
    print("   ПРОБЛЕМА: При выводе используется системный часовой пояс,")
    print("   но это не явно указано в данных!")
    
    # Пример 5: Проблемы с переходом на летнее/зимнее время
    print("\n5. Проблемы с переходом на летнее/зимнее время (DST):")
    print("   В России переход на летнее время отменен, но в других странах")
    print("   (например, в США) есть переходы, которые могут вызвать:")
    print("   - Неоднозначность (одно время может быть в двух часовых поясах)")
    print("   - Пропуск времени (переход на летнее время)")
    print("   - Повторение времени (переход на зимнее время)")
    print("   ПРОБЛЕМА: Наивный подход не учитывает эти случаи!")
    
    # Пример 6: Проблема при сохранении в БД
    print("\n6. Проблема при сохранении в базу данных:")
    print("   Многие БД требуют явного указания часового пояса.")
    print("   Наивная дата может быть интерпретирована по-разному")
    print("   в зависимости от настроек БД!")
    print(f"   Пример: {naive_date} может быть:")
    print("   - 2024-05-13 14:30:00 UTC")
    print("   - 2024-05-13 14:30:00 MSK (UTC+3)")
    print("   - 2024-05-13 14:30:00 в системном часовом поясе")
    print("   ПРОБЛЕМА: Неоднозначность может привести к багам!")


def main():
    """Главная функция для демонстрации проблем"""

    demonstrate_problems()
    



if __name__ == "__main__":
    main()

"""
Пример демонстрации проблемы гонки данных (race condition) в многопоточном программировании.

Этот код демонстрирует классическую проблему синхронизации:
два потока одновременно изменяют общую переменную без синхронизации,
что приводит к непредсказуемым результатам.

ВАЖНО: В Python из-за GIL (Global Interpreter Lock) простые операции с int
могут выполняться атомарно. Чтобы показать проблему, мы используем:
1. Явное разделение операции на шаги
2. time.sleep(0) для принудительного переключения потоков
3. Большое количество итераций
"""

import threading
import time


class ThreadExample:
    # Общая переменная, доступная всем потокам
    counter = 0

    @staticmethod
    def main():
        """
        Основная функция, создающая два потока для инкрементации счетчика.
        
        Ожидаемый результат: counter = 200000 (100000 от каждого потока)
        Реальный результат: непредсказуем, обычно меньше 200000
        """
        # Функция-задача, которую будут выполнять потоки
        def task():
            """
            Задача для каждого потока: инкрементировать counter 100000 раз.
            
            Проблема: операция counter += 1 НЕ является атомарной!
            Она состоит из трех шагов:
            1. Прочитать текущее значение counter
            2. Увеличить его на 1
            3. Записать новое значение обратно
            
            Между этими шагами другой поток может вмешаться и перезаписать значение.
            
            Чтобы сделать проблему более заметной, мы явно разделяем операцию на шаги.
            """
            for i in range(100000):
                # Явно разделяем операцию на шаги, чтобы показать неатомарность
                # Это увеличивает вероятность конфликта между потоками
                current_value = ThreadExample.counter  # Шаг 1: чтение
                # time.sleep(0) принудительно освобождает GIL, позволяя другому потоку выполниться
                # Это увеличивает вероятность того, что другой поток вмешается между шагами
                time.sleep(0)  # Принудительное переключение контекста
                new_value = current_value + 1          # Шаг 2: вычисление
                ThreadExample.counter = new_value      # Шаг 3: запись

        # Создаем два потока с одинаковой задачей
        thread1 = threading.Thread(target=task)
        thread2 = threading.Thread(target=task)

        # Запускаем оба потока
        thread1.start()
        thread2.start()

        # Ждем завершения обоих потоков
        # join() блокирует выполнение до тех пор, пока поток не завершится
        thread1.join()
        thread2.join()

        # Выводим результат
        expected = 200000  # 100000 от каждого потока
        print(f"Counter: {ThreadExample.counter}")
        print(f"Ожидалось: {expected}")
        print(f"Разница: {expected - ThreadExample.counter}")


if __name__ == "__main__":
    # Запускаем программу несколько раз, чтобы показать непредсказуемость
    print("=" * 60)
    print("Демонстрация проблемы гонки данных")
    print("=" * 60)
    print("\nЗапуск 1:")
    ThreadExample.counter = 0
    ThreadExample.main()
    
    print("\nЗапуск 2:")
    ThreadExample.counter = 0
    ThreadExample.main()
    
    print("\nЗапуск 3:")
    ThreadExample.counter = 0
    ThreadExample.main()
    
    print("\n" + "=" * 60)
    print("ПОЯСНЕНИЕ:")
    print("В Python из-за GIL (Global Interpreter Lock) простые операции")
    print("с int могут выполняться атомарно на уровне байт-кода.")
    print("")
    print("Чтобы продемонстрировать проблему гонки данных, мы:")
    print("1. Явно разделили операцию на 3 шага (чтение-вычисление-запись)")
    print("2. Использовали time.sleep(0) для принудительного переключения потоков")
    print("3. Использовали большое количество итераций")
    print("")
    print("В Java эта проблема проявляется сильнее из-за отсутствия GIL.")
    print("=" * 60)


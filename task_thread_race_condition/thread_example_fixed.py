"""
ПРАВИЛЬНОЕ РЕШЕНИЕ: Демонстрация решения проблемы гонки данных
с использованием механизмов синхронизации (Lock/Мьютекс).

Этот код показывает, как правильно синхронизировать доступ к общему ресурсу,
чтобы избежать состояния гонки и гарантировать корректный результат.
"""

import threading
import time


class ThreadExampleFixed:
    """
    Правильная реализация с использованием Lock (мьютекса) для синхронизации.
    
    Lock гарантирует, что только один поток может выполнять критическую секцию
    кода в определенный момент времени, предотвращая состояние гонки.
    """
    # Общая переменная, доступная всем потокам
    counter = 0
    # Мьютекс для синхронизации доступа к counter
    lock = threading.Lock()

    @staticmethod
    def main():
        """
        Основная функция, создающая два потока для инкрементации счетчика.
        
        Ожидаемый результат: counter = 200000 (100000 от каждого потока)
        Реальный результат: всегда 200000 благодаря синхронизации
        """
        def task():
            """
            Задача для каждого потока: инкрементировать counter 100000 раз.
            
            ПРАВИЛЬНОЕ РЕШЕНИЕ: Используем lock для защиты критической секции.
            Операция инкремента теперь атомарна - только один поток может
            выполнять её в определенный момент времени.
            """
            for i in range(100000):
                # Используем контекстный менеджер 'with' для автоматического
                # получения и освобождения блокировки
                with ThreadExampleFixed.lock:
                    # Критическая секция: только один поток может выполнять этот код
                    current_value = ThreadExampleFixed.counter  # Шаг 1: чтение
                    time.sleep(0)  # Даже с задержкой другой поток не может вмешаться
                    new_value = current_value + 1              # Шаг 2: вычисление
                    ThreadExampleFixed.counter = new_value     # Шаг 3: запись
                # Блокировка автоматически освобождается здесь

        # Создаем два потока с одинаковой задачей
        thread1 = threading.Thread(target=task)
        thread2 = threading.Thread(target=task)

        # Запускаем оба потока
        thread1.start()
        thread2.start()

        # Ждем завершения обоих потоков
        # join() блокирует выполнение до тех пор, пока поток не завершится
        thread1.join()
        thread2.join()

        # Выводим результат
        expected = 200000  # 100000 от каждого потока
        print(f"Counter: {ThreadExampleFixed.counter}")
        print(f"Ожидалось: {expected}")
        print(f"Разница: {expected - ThreadExampleFixed.counter}")
        print(f"✓ Результат корректен: {ThreadExampleFixed.counter == expected}")


if __name__ == "__main__":
    print("=" * 60)
    print("ПРАВИЛЬНОЕ РЕШЕНИЕ: Синхронизация с использованием Lock")
    print("=" * 60)
    
    ThreadExampleFixed.counter = 0
    ThreadExampleFixed.main()
    
 

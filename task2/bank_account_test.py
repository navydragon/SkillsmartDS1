"""
Тестовый класс для демонстрации работы BankAccount
Показывает, что код работает без исключений, но содержит логические ошибки
"""

from bank_account import BankAccount


def main():
    print("=== Тестирование BankAccount ===\n")
    
    # Создаём счёт с начальным балансом
    account = BankAccount(1000.0)
    print(f"1. Создан счёт с начальным балансом: {account.get_balance()}")
    
    # Нормальная операция - пополнение
    account.deposit(500.0)
    print(f"2. После пополнения на 500: {account.get_balance()}")
    
    # Нормальная операция - снятие
    account.withdraw(200.0)
    print(f"3. После снятия 200: {account.get_balance()}")
    
    # БАГ: пополнение отрицательной суммой (должно быть запрещено, но работает)
    account.deposit(-100.0)
    print(f"4. После 'пополнения' на -100 (БАГ!): {account.get_balance()}")
    
    # БАГ: снятие отрицательной суммой (должно быть запрещено, но работает)
    account.withdraw(-50.0)
    print(f"5. После 'снятия' -50 (БАГ!): {account.get_balance()}")
    
    # БАГ: снятие суммы больше баланса (баланс становится отрицательным)
    account.withdraw(2000.0)
    print(f"6. После снятия 2000 при балансе ~1150 (БАГ!): {account.get_balance()}")
    
    # БАГ: ещё одно снятие при отрицательном балансе
    account.withdraw(500.0)
    print(f"7. После снятия 500 при отрицательном балансе (БАГ!): {account.get_balance()}")
    
    # БАГ: пополнение отрицательной суммой при отрицательном балансе
    account.deposit(-200.0)
    print(f"8. После 'пополнения' -200 (БАГ!): {account.get_balance()}")
    
    print(f"\n=== Итоговый баланс: {account.get_balance()} ===")
    print("\nВывод: Код работает без исключений, но содержит серьёзные логические ошибки!")
    print("Проблемы:")
    print("  - Принимаются отрицательные суммы")
    print("  - Баланс может стать отрицательным")
    print("  - Нет валидации входных данных")


if __name__ == "__main__":
    main()


"""
Класс BankAccount - демонстрация ложной уверенности в коде.
Код работает без исключений, но содержит логические ошибки:
- нет проверки на отрицательные суммы в deposit и withdraw
- баланс может стать отрицательным при снятии средств
"""


class BankAccount:
    """
    Класс банковского счёта с намеренными багами.
    Демонстрирует проблему ложной уверенности в коде.
    """
    
    def __init__(self, initial_balance: float):
        """
        Конструктор создаёт банковский счёт с начальным балансом
        
        Args:
            initial_balance: начальный баланс счёта
        """
        self.__balance = initial_balance
    
    def deposit(self, amount: float) -> None:
        """
        Метод для пополнения счёта
        БАГ: нет проверки на отрицательную сумму
        
        Args:
            amount: сумма для пополнения
        """
        self.__balance += amount
    
    def withdraw(self, amount: float) -> None:
        """
        Метод для снятия средств со счёта
        БАГ: нет проверки на отрицательную сумму
        БАГ: баланс может стать отрицательным
        
        Args:
            amount: сумма для снятия
        """
        self.__balance -= amount
    
    def get_balance(self) -> float:
        """
        Метод для получения текущего баланса
        
        Returns:
            текущий баланс счёта
        """
        return self.__balance

